#!/usr/bin/env python3
"""Prepare static JSON assets for the GitHub Pages match simulator."""
import json, shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"site"/"data"
PROCESSED=ROOT/"data"/"processed"
OUT.mkdir(parents=True,exist_ok=True)
for name in ("current_player_states.json","prediction_model.json"):
    src=PROCESSED/name
    if not src.exists(): raise SystemExit(f"Missing required model artifact: {src}")
    shutil.copy2(src,OUT/name)
    print(f"Published {name}: {src.stat().st_size:,} bytes")

# Publish descriptive domestic player records for the searchable history panel.
# This file is generated by the scheduled DataSportsAPI refresh. If a deploy-only
# build has no fresh processed copy, preserve the last committed site asset.
domestic=PROCESSED/"datasportsapi_player_records.json"
if domestic.exists():
    shutil.copy2(domestic,OUT/"datasportsapi_player_records.json")
    print(f"Published domestic player history index: {domestic.stat().st_size:,} bytes")
elif (OUT/"datasportsapi_player_records.json").exists():
    print("Preserving last published domestic player history index.")
else:
    print("Domestic player history index not available yet; panel will show unavailable status.")
